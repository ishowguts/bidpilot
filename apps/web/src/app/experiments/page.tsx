'use client';
import {
  Bar,
  BarChart,
  CartesianGrid,
  ErrorBar,
  Legend,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import { api } from '@/lib/api';
import { POLICY_ORDER, cpaBars, rowLabel, type ResultRow } from '@/lib/experiments';
import { inr, int, pct, signedPct } from '@/lib/format';
import { useApi } from '@/lib/useApi';
import { Card, ErrorBox, Loading } from '@/components/ui';

const COLORS: Record<string, string> = {
  equal: '#94a3b8',
  greedy: '#ca8a04',
  thompson: '#4f46e5',
  oracle: '#16a34a',
};

const ci = (mean: string, half: string) => (
  <>
    {mean} <span className="text-slate-400">± {half}</span>
  </>
);

export default function ExperimentsPage() {
  const { data, error, reload } = useApi(() => api.experiments(), 'experiments');
  if (error) return <ErrorBox error={error} onRetry={reload} />;
  if (!data) return <Loading />;
  const scenarios = [...new Set(data.rows.map((r) => r.scenario))];

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-xl font-semibold">Experiments</h1>
        <p className="text-sm text-slate-500">
          {data.options.seeds} seeds × {data.options.days} days, {inr(data.options.dailyBudget)}/day, same
          traffic for every policy on a seed. Means with 95% confidence intervals. Generated by{' '}
          <code>{data.command}</code> at commit <code>{data.commit}</code>.
        </p>
      </div>

      <Card title="Cost per apply by policy and scenario (95% CI)">
        <div className="h-72">
          <ResponsiveContainer width="100%" height="100%">
            <BarChart data={cpaBars(data.rows)}>
              <CartesianGrid strokeDasharray="3 3" stroke="#e2e8f0" />
              <XAxis dataKey="scenario" fontSize={12} />
              <YAxis fontSize={12} tickFormatter={(v: number) => inr(v)} width={72} />
              <Tooltip formatter={(v: number) => inr(v)} />
              <Legend />
              {POLICY_ORDER.map((p) => (
                <Bar key={p} dataKey={p} fill={COLORS[p]} isAnimationActive={false}>
                  <ErrorBar dataKey={`${p}Ci`} width={4} stroke="#0f172a" />
                </Bar>
              ))}
            </BarChart>
          </ResponsiveContainer>
        </div>
      </Card>

      {scenarios.map((scenario) => (
        <Card key={scenario} title={`Scenario: ${scenario}`}>
          <ResultsTable rows={data.rows.filter((r) => r.scenario === scenario)} seeds={data.options.seeds} />
        </Card>
      ))}
    </div>
  );
}

function ResultsTable({ rows, seeds }: { rows: ResultRow[]; seeds: number }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full text-right text-sm tabular-nums">
        <thead className="text-xs uppercase text-slate-500">
          <tr>
            <th className="py-2 pr-3 text-left">Policy</th>
            <th className="py-2 pr-3">Applies</th>
            <th className="py-2 pr-3">CPA</th>
            <th className="py-2 pr-3">CPA vs equal</th>
            <th className="py-2 pr-3">Regret (applies)</th>
            <th className="py-2 pr-3">Beats equal</th>
            <th className="py-2 pr-3">Beats greedy</th>
            <th className="py-2 pr-3">Pacing</th>
            <th className="py-2">Overdelivery days</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-slate-100">
          {rows.map((r) => (
            <tr key={rowLabel(r)} className={r.floor === undefined ? '' : 'text-slate-500'}>
              <td className="py-2 pr-3 text-left">{rowLabel(r)}</td>
              <td className="py-2 pr-3">
                {ci(int(Math.round(r.applies.mean)), int(Math.round(r.applies.ci)))}
              </td>
              <td className="py-2 pr-3">{ci(inr(r.cpa.mean), inr(r.cpa.ci))}</td>
              <td className="py-2 pr-3">
                {ci(signedPct(r.cpaVsEqualPct.mean), `${r.cpaVsEqualPct.ci.toFixed(1)}%`)}
              </td>
              <td className="py-2 pr-3">
                {ci(int(Math.round(r.regret.mean)), int(Math.round(r.regret.ci)))}
              </td>
              <td className="py-2 pr-3">{r.policy === 'equal' ? '—' : `${r.winsVsEqual}/${seeds}`}</td>
              <td className="py-2 pr-3">{r.policy === 'greedy' ? '—' : `${r.winsVsGreedy}/${seeds}`}</td>
              <td className="py-2 pr-3">{pct(r.pacingRatio)}</td>
              <td className="py-2">{r.overdeliveryDays}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
